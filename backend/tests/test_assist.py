import os
import unittest
from unittest.mock import patch

from assist import create_assist_reply, reply_uses_expected_script, resolve_spoken_language


class LocalAssistTests(unittest.IsolatedAsyncioTestCase):
    async def test_electrical_context_returns_local_safety_guidance_without_key(self) -> None:
        messages = [{"role": "user", "content": "What should I inspect first?"}]
        context = {
            "assetId": "ELEC-118",
            "site": "Distribution Room 2",
            "issue": "Electrical fault",
            "description": "Breaker trips under load",
            "severity": "Critical",
        }

        with patch.dict(os.environ, {"OPENAI_API_KEY": ""}):
            reply, provider = await create_assist_reply(messages, context)

        self.assertEqual(provider, "local")
        self.assertIn("lockout/tagout", reply)
        self.assertIn("Severity is Critical", reply)
        self.assertIn("not generated by an LLM", reply)


class SpokenLanguageTests(unittest.TestCase):
    def test_tamil_script_corrects_a_hindi_transcription_label(self) -> None:
        language, locale = resolve_spoken_language("hindi", "தமிழில் பேசுகிறேன்")
        self.assertEqual(language, "Tamil")
        self.assertEqual(locale, "ta-IN")

    def test_hindi_script_resolves_to_hindi_locale(self) -> None:
        language, locale = resolve_spoken_language("hi", "मुझे जांच में मदद चाहिए")
        self.assertEqual(language, "Hindi")
        self.assertEqual(locale, "hi-IN")

    def test_tamil_language_name_resolves_to_tamil_locale(self) -> None:
        language, locale = resolve_spoken_language("Tamil", "Check the motor")
        self.assertEqual(language, "Tamil")
        self.assertEqual(locale, "ta-IN")

    def test_typed_tamil_text_resolves_to_tamil_locale(self) -> None:
        language, locale = resolve_spoken_language("", "இதை தமிழில் விளக்கவும்")
        self.assertEqual(language, "Tamil")
        self.assertEqual(locale, "ta-IN")

    def test_typed_bengali_text_resolves_to_bengali_locale(self) -> None:
        language, locale = resolve_spoken_language("", "এটি কীভাবে পরীক্ষা করব")
        self.assertEqual(language, "Bengali")
        self.assertEqual(locale, "bn-IN")

    def test_english_reply_is_rejected_for_tamil_locale(self) -> None:
        self.assertFalse(reply_uses_expected_script("Check the air filter first.", "ta-IN"))

    def test_tamil_reply_is_accepted_for_tamil_locale(self) -> None:
        self.assertTrue(reply_uses_expected_script("முதலில் காற்று வடிகட்டியைச் சரிபார்க்கவும்.", "ta-IN"))


if __name__ == "__main__":
    unittest.main()